// Uses tsx because the package ships extensionless ESM imports.
// Generates Material 3 color tokens from the SignaVis brand colours (brand/README.md).
// Run: npx tsx scripts/m3-tokens.mjs > src/styles/m3-tokens.css
import { argbFromHex, hexFromArgb, DynamicScheme, Hct, TonalPalette, Variant } from '@material/material-color-utilities';
// Primary = call amber (the contour in the mark), secondary + neutrals = night blue
// (the mark's ground), tertiary = moss.
const BRAND = { amber: '#F2B544', night: '#102A35', moss: '#4E8F6A' };
const hct = (hex) => Hct.fromInt(argbFromHex(hex));
const nightHue = hct(BRAND.night).hue;
const palettes = {
  primaryPalette: TonalPalette.fromHct(hct(BRAND.amber)),
  secondaryPalette: TonalPalette.fromHueAndChroma(nightHue, 18),
  tertiaryPalette: TonalPalette.fromHct(hct(BRAND.moss)),
  neutralPalette: TonalPalette.fromHueAndChroma(nightHue, 7),
  neutralVariantPalette: TonalPalette.fromHueAndChroma(nightHue, 12),
};
const SEED = BRAND.amber;
const roles = ['primary','onPrimary','primaryContainer','onPrimaryContainer','secondary','onSecondary','secondaryContainer','onSecondaryContainer','tertiary','onTertiary','tertiaryContainer','onTertiaryContainer','surface','onSurface','onSurfaceVariant','surfaceContainerLowest','surfaceContainerLow','surfaceContainer','surfaceContainerHigh','surfaceContainerHighest','outline','outlineVariant','error','onError','inverseSurface','inverseOnSurface'];
const kebab = s => s.replace(/[A-Z]/g, m => '-' + m.toLowerCase());
const block = (dark) => {
  const s = new DynamicScheme({ sourceColorHct: hct(SEED), variant: Variant.TONAL_SPOT, contrastLevel: 0, isDark: dark, ...palettes });
  return roles.map(r => `  --md-${kebab(r)}: ${hexFromArgb(s[r])};`).join('\n');
};
console.log(`/* Generated by scripts/m3-tokens.mjs from the brand colours (amber ${BRAND.amber}, night ${BRAND.night}, moss ${BRAND.moss}). Do not edit by hand. */
:root, :root[data-theme='dark'] {\n${block(true)}\n}
:root[data-theme='light'] {\n${block(false)}\n}`);
