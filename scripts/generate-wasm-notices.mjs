#!/usr/bin/env node
// Writes the license texts of every crate compiled into aw_dsp_wasm_bg.wasm
// to src-tauri/crates/aw-dsp-wasm/THIRD_PARTY_LICENSES.txt.
// Rerun after changing the crate's dependencies: npm run notices:wasm
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const crateDir = join(root, 'src-tauri/crates/aw-dsp-wasm');
const out = join(crateDir, 'THIRD_PARTY_LICENSES.txt');

const meta = JSON.parse(
    execFileSync(
        'cargo',
        ['metadata', '--format-version', '1', '--filter-platform', 'wasm32-unknown-unknown'],
        { cwd: crateDir, maxBuffer: 64 * 1024 * 1024 },
    ).toString(),
);

const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const normal = (dep) => dep.dep_kinds.some((k) => k.kind === null);

const seen = new Set();
const stack = [meta.resolve.root];
while (stack.length) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const dep of nodes.get(id).deps) if (normal(dep)) stack.push(dep.pkg);
}

const licenseFiles = (dir) =>
    readdirSync(dir)
        .filter((f) => /^(licen[cs]e|copying|notice)/i.test(f))
        .sort();

const sections = [];
for (const id of seen) {
    const p = byId.get(id);
    if (p.source === null) continue;
    const dir = dirname(p.manifest_path);
    const files = licenseFiles(dir);
    if (!files.length) throw new Error(`${p.name} ${p.version}: no license file in ${dir}`);
    const texts = files.map((f) => `--- ${f} ---\n\n${readFileSync(join(dir, f), 'utf8').trim()}`);
    sections.push(`${p.name} ${p.version} (${p.license})\n${p.repository ?? ''}\n\n${texts.join('\n\n')}`);
}
sections.sort();

const rule = '='.repeat(78);
writeFileSync(
    out,
    `Third-party software compiled into aw_dsp_wasm_bg.wasm\n` +
        `(generated by scripts/generate-wasm-notices.mjs)\n\n${rule}\n` +
        sections.join(`\n\n${rule}\n`) +
        '\n',
);
console.log(`${sections.length} crates -> ${out}`);
