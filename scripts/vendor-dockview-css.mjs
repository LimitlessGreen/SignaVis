// Copy dockview-core's stylesheet into src/styles/vendor/dockview.css.
// The package's ESM build ships no CSS; only its UMD build injects it from a
// string. Run after updating dockview-core:  node scripts/vendor-dockview-css.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const pkgDir = path.join(ROOT, 'node_modules', 'dockview-core');
const { version } = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
const umd = fs.readFileSync(path.join(pkgDir, 'dist', 'dockview-core.js'), 'utf8');
const m = umd.match(/s\.textContent = ("(?:[^"\\]|\\.)*");/);
if (!m) throw new Error('stylesheet string not found in dockview-core.js');
const css = JSON.parse(m[1]);
const out = path.join(ROOT, 'src', 'styles', 'vendor', 'dockview.css');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `/* dockview-core ${version} stylesheet (MIT, https://github.com/dockview/dockview).
   Generated by scripts/vendor-dockview-css.mjs — do not edit. */\n${css}`);
console.log(`wrote ${path.relative(ROOT, out)} (${css.length} chars, dockview-core ${version})`);
