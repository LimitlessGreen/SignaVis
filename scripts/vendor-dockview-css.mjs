// Copy dockview-core's stylesheet into src/styles/vendor/dockview.css.
// The package's ESM build ships no CSS; only its UMD build injects it from a
// string. Run after updating dockview-core:  node scripts/vendor-dockview-css.mjs
import fs from 'node:fs';
import path from 'node:path';
import { isMain } from './is-main.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
export const VENDORED_CSS = path.join(ROOT, 'src', 'styles', 'vendor', 'dockview.css');

/** The stylesheet of the installed dockview-core, with its version and licence text. */
export function dockviewCss(pkgDir = path.join(ROOT, 'node_modules', 'dockview-core')) {
    const { version } = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
    const umd = fs.readFileSync(path.join(pkgDir, 'dist', 'dockview-core.js'), 'utf8');
    const m = umd.match(/s\.textContent = ("(?:[^"\\]|\\.)*");/);
    if (!m) throw new Error('stylesheet string not found in dockview-core.js');
    const licence = fs.readFileSync(path.join(pkgDir, 'LICENCE.md'), 'utf8').trim();
    return { version, licence, css: JSON.parse(m[1]) };
}

/** File content: header (version, full MIT notice) + stylesheet. */
export function vendoredFile({ version, licence, css }) {
    return `/* dockview-core ${version} stylesheet (https://github.com/dockview/dockview).
   Generated by scripts/vendor-dockview-css.mjs — do not edit.

${licence.replace(/\*\//g, '* /')}
*/
${css}`;
}

if (isMain(import.meta.url)) {
    const d = dockviewCss();
    fs.mkdirSync(path.dirname(VENDORED_CSS), { recursive: true });
    fs.writeFileSync(VENDORED_CSS, vendoredFile(d));
    console.log(`wrote ${path.relative(ROOT, VENDORED_CSS)} (${d.css.length} chars, dockview-core ${d.version})`);
}
